"""Cut a 16x16 head portrait of every monster into hooks/gen/heads.ts (spec 5.2 HUD icons).

Each portrait comes from the first IDLE frame in hooks/gen/<group>.ts: a square
window sized by the head hurt box of hooks/collision-data.ts (its longer edge x 1.3)
and placed at the snout, the leftmost opaque pixels, area-averaged down to 16x16 (alpha cut at half), then mapped onto
the monster's own palette. The art faces left as drawn; nothing is mirrored.
The output is run-length encoded like the other gen files, one palette per
monster, so nothing is cropped at run time.

Usage: PYTHONUTF8=1 python -I tools/make_heads.py
(Re-run after changing a monster's IDLE art or head box.)
"""
import json
import os
import re

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
GEN = os.path.join(HERE, '..', 'hooks', 'gen')
BOXES = os.path.join(HERE, '..', 'hooks', 'collision-data.ts')
SIZE = 16
WINDOW = 1.3
# monster id -> (gen file, IDLE action); the order is the registry's (hooks/monsters/registry.ts)
MONSTERS = [
    ('velkhana', 'vel', 'V01'),
    ('great_jagras', 'jagras', 'JG_IDLE'),
    ('tobi_kadachi', 'tobi', 'TK_IDLE'),
    ('anjanath', 'anjanath', 'AN_IDLE'),
    ('barioth', 'barioth', 'BA_IDLE'),
    ('nargacuga', 'narga', 'NA_IDLE'),
    ('tigrex', 'tigrex', 'TI_IDLE'),
    ('zinogre', 'zinogre', 'ZI_IDLE'),
    ('ruiner_nergigante', 'nergi', 'RN_IDLE'),
]
CHARS = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ'


def load_ts(path):
    text = open(path, encoding='utf-8').read()
    start = text.index('= ', text.index('export const')) + 2
    end = text.rindex(' as const') if ' as const' in text else len(text)
    return json.loads(text[start:end])


def decode(row):
    out = []
    for ch, n in re.findall(r'([a-zA-Z.])(\d*)', row):
        out += [ch] * (int(n) if n else 1)
    return out


def rle(row):
    out, x = [], 0
    while x < len(row):
        e = x + 1
        while e < len(row) and row[e] == row[x]:
            e += 1
        out.append(row[x] + (str(e - x) if e - x > 1 else ''))
        x = e
    return ''.join(out)


def hex_rgb(c):
    return tuple(int(c[i:i + 2], 16) for i in (1, 3, 5))


def portrait(group, action, head):
    pal = group['palette']
    sprite = group['actions'][action]
    rows = sprite['frames'][0]
    h, w = len(rows), max(len(decode(r)) for r in rows)
    img = Image.new('RGBA', (w, h), (0, 0, 0, 0))
    px = img.load()
    for y, row in enumerate(rows):
        for x, ch in enumerate(decode(row)):
            if ch != '.':
                px[x, y] = hex_rgb(pal[ch]) + (255,)
    # local box (feet at 0, anchor at x=0) -> pixels
    x0, y0, x1, y1 = head
    # the hurt box only says how big a head is: the window starts at the snout (the leftmost
    # opaque column) and sits at the height of the pixels near it
    side = round(max(x1 - x0, y1 - y0) * WINDOW)
    alpha = img.getchannel('A').load()
    left = min(x for x in range(w) if any(alpha[x, y] for y in range(h)))
    near = sorted(y for x in range(left, left + side // 2) for y in range(h) if alpha[x, y])
    cy = near[len(near) // 2]
    left, top = left - 1, round(cy - side / 2)
    win = Image.new('RGBA', (side, side), (0, 0, 0, 0))
    win.paste(img, (-left, -top))
    small = win.resize((SIZE, SIZE), Image.BOX)
    sp = small.load()
    names = sorted(pal)
    colors = {n: hex_rgb(pal[n]) for n in names}
    grid = []
    used = {}
    for y in range(SIZE):
        line = []
        for x in range(SIZE):
            r, g, b, a = sp[x, y]
            if a < 128:
                line.append('.')
                continue
            best = min(names, key=lambda n: sum((u - v) ** 2 for u, v in zip(colors[n], (r, g, b))))
            used[best] = pal[best]
            line.append(best)
        grid.append(''.join(line))
    return {'palette': used, 'rows': [rle(r) for r in grid]}


def main():
    boxes_text = open(BOXES, encoding='utf-8').read()
    boxes = json.loads(boxes_text[boxes_text.index('BOXES: Readonly<Record<ActionId, ActionBoxes>> = ') + len('BOXES: Readonly<Record<ActionId, ActionBoxes>> = '):])
    out = {}
    for mid, gen, action in MONSTERS:
        group = load_ts(os.path.join(GEN, gen + '.ts'))
        head = boxes[action]['hurt'][0]['head']
        out[mid] = portrait(group, action, head)
        print(mid, action, head, len(out[mid]['palette']), 'colours')
    path = os.path.join(GEN, 'heads.ts')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/make_heads.py from the IDLE frames and head boxes. Do not edit by hand.\n')
        f.write('export const HEADS = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ' as const\n')
    print('wrote', path)


if __name__ == '__main__':
    main()
