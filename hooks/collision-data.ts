/**
 * Hand-measured collision boxes, in each action's local frame: x = u - anchorX
 * on the unmirrored sprite, y = v - height (feet at 0, body at negative y).
 * Each box is [minX, minY, maxX, maxY]. Measured from the extracted frames
 * (hooks/gen) on a grid; they are this project's adaptation, not game data.
 *
 * `hurt` lists, per pose, the parts that can be hit; one entry stands for
 * every pose. `hit` is the attack's box on its active pose (data.ts `active`).
 *
 * Great Jagras (JG_*) boxes are this project's grey-box values (spec 3.4),
 * fitted to each extracted pose on a 10px grid; `belly` exists only on the
 * poses drawn inflated. Its spit (JG04) is a projectile: the box is where the
 * ball leaves the mouth, moved by the engine as it flies.
 *
 * Tobi-Kadachi (TK_*) boxes start from the same grey-box table, fitted the
 * same way. TK02 is a leap: the art stays on the ground line and the engine
 * lifts the root (moves' `lift`), so these boxes rise with it. TK03 sweeps
 * the tail round both sides; TK04's box covers the slam's splash in front.
 *
 * Anjanath (AN_*) likewise. AN03 has no head box while it turns away (the
 * head is hidden behind the body); AN04's breath is three boxes of one group
 * straight ahead of the mouth, so it settles once.
 *
 * Barioth (BA_*) boxes are proposed from each extracted frame (head at the
 * front, tail at the back, spec 3.4 widths) and checked on the grid preview;
 * its two wings (near and far side, spec 3.4 allows that naming) are boxes on
 * the back of every pose. BA04's box is the whirlwind 100 px ahead (ticks 12..27).
 *
 * Nargacuga (NA_*) boxes are proposed from each frame the same way (body
 * top capped below the raised tail); NA02 F2 and NA04 F2 are drawn turned
 * round, head at the right. NA03X is the enraged double slam from the combo
 * board: its two slams are `hit` and `more`. NA04's three boxes are the spike
 * volley at the tail tip, moved by the engine as it flies and spreads.
 *
 * Tigrex (TI_*) likewise. TI01X is the turn-back dash from the combo board:
 * left dash, brake turning right, right dash, brake turning left, left dash,
 * recover; its frames 1 and 2 are drawn facing right (head at the right) and
 * each dash is its own hit pose (`hit`, then `more`).
 *
 * Zinogre (ZI_*) likewise. ZI01X is the three-paw combo: six poses from the
 * combo board and a seventh (recover) from its own board; each paw is a hit
 * pose (`hit`, then `more`). ZI04's box is the thunder ring as one AABB.
 *
 * The object below is plain JSON so tools can read it without TypeScript.
 */
export type LocalBox = readonly [number, number, number, number]
export type Part =
  | 'hunter_body'
  | 'head'
  | 'body'
  | 'tail'
  | 'belly'
  | 'wing_near'
  | 'wing_far'
  | 'spike_head'
  | 'spike_arm_near'
  | 'spike_arm_far'
export type PoseHurt = Readonly<Partial<Record<Part, LocalBox>>>
export type HitDef = { pose: number; boxes: readonly LocalBox[] }
/** `hit` is the first (or only) attack pose; `more` the other poses of a combo, each its own group. */
export type ActionBoxes = { hurt: readonly PoseHurt[]; hit?: HitDef; more?: readonly HitDef[] }

